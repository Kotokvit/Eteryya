# C3. МЕХАНИКА КОГТЕЙ: ИМПУЛЬС, КРОМКА, ДАВЛЕНИЕ СРЕЗА
# ════════════════════════════════════════════════════════════════════════════
print()
print("C3. Механика шунта: импульс и мономолекулярная кромка")
print("-" * 70)
V_JUMP, M_JUMP = 14.0, 5.0
p_imp = M_JUMP * V_JUMP
E_kin = 0.5 * M_JUMP * V_JUMP ** 2
DEPTH = 0.023                    # 18 мм + 5 мм проворота
t_pierce = DEPTH / V_JUMP
F_avg = p_imp / t_pierce
A_edge = 5 * (0.3e-9 * 18e-3)    # 5 когтей x кромка (0.3 нм x 18 мм)
P_cut = F_avg / A_edge
print(f"  Прыжок 5 кг гиперплотной материи: v = {V_JUMP} м/с в узел 6 меридианов")
print(f"    импульс p = {p_imp:.0f} Н*с; кинетическая энергия E = {E_kin:.0f} Дж")
print(f"    (энергия удара — миллионные доли сброса: акт АППАРАТНЫЙ, не энергетический)")
print(f"  Проникновение: глубина {DEPTH*1000:.0f} мм за {t_pierce*1e3:.2f} мс")
print(f"    Средняя сила: F = p/dt = {F_avg/1e3:.1f} кН на 5 когтей")
print(f"  Кромка: 5 x (0.3 нм x 18 мм) = {A_edge:.2e} м^2")
print(f"    Давление среза: P = F/A = {P_cut:.2e} Па = {P_cut/1e15:.2f} ППа")
print(f"    Прочность кости ~160 МПа -> кромка выше на x{P_cut/1.6e8:.1e}")
print("    -> «Пробитие 3-4-5 межреберий» — механически тривиально;")
print("       стоп в 3 мм от миокарда — управляемое гашение импульса.")
chk("C3-a импульс шунта, Н*с", p_imp, 70.0, 0.5)
chk("C3-b кинетическая энергия, Дж", E_kin, 490.0, 1.0)
chk("C3-c давление среза > 1e15 Па (кость x1e7)", 1.0 if P_cut > 1e15 else 0.0, 1.0)
results["C_mechanics"] = {
    "impulse_N_s": p_imp, "kinetic_J": E_kin,
    "pierce_time_ms": t_pierce * 1e3, "avg_force_kN": F_avg / 1e3,
    "edge_area_m2": A_edge, "cut_pressure_Pa": P_cut,
}

# ════════════════════════════════════════════════════════════════════════════
# C4. РАДИАЦИОННЫЙ КАСКАД chi-антенн ШЕРСТИ
# ════════════════════════════════════════════════════════════════════════════
print()
print("C4. Радиационный каскад: шерсть 4 -> 11 мм (площадь x17)")
print("-" * 70)
A_base = 0.13                   # м^2 — поверхность Соболя
A_eff = 17 * A_base
eps_fur = 0.9
waves = []
print(f"  Эффективная площадь излучения: {A_base:.2f} м^2 x 17 = {A_eff:.2f} м^2")
print(f"  Волны сброса (излучение по Стефану-Больцману, eps = {eps_fur}):")
for i, T_wave in enumerate((1573.15, 1373.15, 1173.15), 1):   # 1300/1100/900 C
    P_rad = eps_fur * sc.Stefan_Boltzmann * A_eff * (T_wave ** 4 - T_BODY ** 4)
    t_wave = 0.8 if i == 1 else 0.4
    E_rad = P_rad * t_wave
    waves.append({"wave": i, "T_K": T_wave, "T_C": T_wave - 273.15,
                  "P_kW": P_rad / 1e3, "t_s": t_wave, "E_MJ": E_rad / 1e6})
    print(f"    Волна {i}: T = {T_wave-273.15:.0f} C: P = {P_rad/1e3:6.0f} кВт x {t_wave} c"
          f" = {E_rad/1e6:.3f} МДж")
E_rad_total = sum(w["E_MJ"] for w in waves)
share_rad = E_rad_total / Q_PANIC * 1e6
print(f"  Суммарно излучение: {E_rad_total:.2f} МДж = {share_rad:.1f}% сброса")
print("  -> Радиация — вторичный канал; главный сток — испарение воды тела (C1)")
print("     и теплопроводность шунта в печать. Каскад волн гасит остаточный")
print("     дефицит после дегидратации, остекляя породу (платиновый диск,")
print("     адамантит -> черное стекло).")
chk("C4-a радиационная доля < 5%", 1.0 if share_rad < 5 else 0.0, 1.0)
results["C_radiation"] = {"waves": waves, "E_total_MJ": E_rad_total,
                          "share_of_dump_pct": share_rad}

